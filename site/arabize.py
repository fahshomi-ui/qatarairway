path = "airports.js"
src = open(path, encoding="utf-8").read()

# Only touch the city field: c:"<City>, <country>"
def repl(m):
    city = m.group(1)
    rest = m.group(2)
    return 'c:"%s%s' % (MAP.get(city, city), rest)

out = re.sub(r'c:"([^",]+)(,[^"]*")', repl, src)

# Report anything still Latin
leftover = sorted(set(re.findall(r'c:"([A-Za-z][^",]*)', out)))
open(path, "w", encoding="utf-8").write(out)
